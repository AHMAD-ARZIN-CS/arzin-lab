// New practice problems from your lecture slides or any topic.
// The AI writes the problem AND a reference solution; the expected outputs are then produced by
// actually compiling and running that solution in the sandbox. Problems whose solution doesn't
// compile or crashes are thrown away. (If the reference solution itself is subtly wrong, the
// tests are wrong too — they're marked as generated so you know to be a little skeptical.)
import crypto from 'node:crypto'
import fs from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { ask } from './ai.js'
import { META_DIR, ROOT } from './config.js'
import { toRel } from './files.js'
import { languageFor } from './languages.js'
import { lectureText } from './lectures.js'
import { compile, runOnce } from './runner.js'
import { toContainerPath } from './sandbox.js'

export interface GenRequest { lecture?: string; topic?: string; count?: number; difficulty?: string; level?: string }

const SYSTEM = `You write programming practice problems for a CS student learning C++ (fundamentals through data structures and algorithms).
Output ONLY one JSON object, no prose, no markdown fences.`

function prompt(req: GenRequest, source: string) {
  const n = Math.min(Math.max(req.count ?? 3, 1), 5)
  return `${source}

Write ${n} practice problem(s) of ${req.difficulty ?? 'mixed'} difficulty${req.level ? ` for a learner who is ${req.level}` : ''}.
Each must practice the concepts above, be solvable in a single C++ file reading stdin and writing stdout, and have a precise input/output format.
Vary them: e.g. one direct application, one that combines ideas, one with a tricky edge case.

JSON shape:
{"problems":[{
  "title": "short title",
  "topic": "the concept it practices",
  "difficulty": "easy" | "medium" | "hard",
  "statement": "Markdown: the task, exact Input format, exact Output format, constraints. Do NOT include example outputs (they are generated by running your solution).",
  "starter": "C++ starter: includes, main() that reads the input as described, and a // your code here comment. Must compile. Must NOT contain the solution.",
  "solution": "Complete, correct C++17 reference solution. Read exactly the input format, print exactly the output format, no extra prompts or text.",
  "tests": [{"name": "short description", "input": "stdin text with \\n newlines"}]
}]}
Give 5-7 tests per problem, including edge cases (smallest input, duplicates, negatives, boundaries) that a typical mistake would fail.`
}

function extractJson(text: string) {
  const a = text.indexOf('{'), b = text.lastIndexOf('}')
  if (a < 0 || b < a) throw new Error('The AI did not return problems in the expected format.')
  return JSON.parse(text.slice(a, b + 1))
}

const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 48) || 'problem'

function askOnce(p: string): Promise<string> {
  return new Promise((resolve, reject) => {
    let text = ''
    ask(p, { system: SYSTEM }, {
      delta: (t) => { text += t },
      done: (r) => (r.error ? reject(new Error(r.error)) : resolve(text)),
    })
  })
}

export async function generateProblems(req: GenRequest, progress: (msg: string) => void) {
  let source: string
  let origin: string
  if (req.lecture) {
    const l = await lectureText(req.lecture, 40_000)
    source = `Base the problems on these lecture slides ("${l.title}"):\n\n${l.text}`
    origin = `lecture: ${l.title}`
  } else if (req.topic?.trim()) {
    source = `Topic to practice: ${req.topic.trim()}`
    origin = `topic: ${req.topic.trim()}`
  } else throw new Error('Pick a lecture or type a topic.')

  progress('Asking the AI to write problems and reference solutions…')
  const data = extractJson(await askOnce(prompt(req, source)))
  const lang = languageFor('x.cpp')!
  const created: { title: string; starter: string; tests: number }[] = []
  const skipped: { title: string; reason: string }[] = []
  const work = path.join(META_DIR, 'tmp', 'gen', crypto.randomBytes(4).toString('hex'))

  for (const p of (data.problems ?? []) as { title: string; topic: string; difficulty: string; statement: string; starter: string; solution: string; tests: { name: string; input: string }[] }[]) {
    const title = String(p.title ?? 'Untitled')
    progress(`Checking "${title}": compiling the reference solution in the sandbox…`)
    let slug = slugify(title)
    for (let i = 2; existsSync(path.join(ROOT, 'practice', slug)); i++) slug = `${slugify(title)}-${i}`
    const dir = path.join(work, slug)
    await fs.mkdir(dir, { recursive: true })
    await fs.writeFile(path.join(dir, 'solution.cpp'), String(p.solution ?? ''))
    await fs.writeFile(path.join(dir, 'starter.cpp'), String(p.starter ?? ''))
    const solRel = toRel(path.join(dir, 'solution.cpp'))
    const build = `/tmp/lab/build/gen_${slug.replace(/\W/g, '_')}`
    const c = await compile(solRel, lang, toContainerPath(solRel), build)
    if (!c.ok) { skipped.push({ title, reason: 'reference solution did not compile' }); continue }
    const st = await compile(toRel(path.join(dir, 'starter.cpp')), lang)
    const starter = st.ok ? String(p.starter) : '#include <iostream>\nusing namespace std;\n\nint main() {\n    // your code here\n    return 0;\n}\n'

    progress(`Checking "${title}": running ${p.tests?.length ?? 0} tests to get the expected outputs…`)
    const tests = []
    for (const t of p.tests ?? []) {
      const r = await runOnce(lang, toContainerPath(solRel), build, String(t.input ?? ''), 10)
      if (r.code === 0) tests.push({ name: String(t.name ?? `test ${tests.length + 1}`), input: String(t.input ?? ''), expected: r.stdout.replace(/\s+$/, '') })
    }
    if (tests.length < 3) { skipped.push({ title, reason: `only ${tests.length} test(s) ran cleanly` }); continue }

    const ex = tests[0]
    const statement = `# ${title}\n\n${String(p.statement ?? '').trim()}\n\n**Example**\n\nInput\n\`\`\`\n${ex.input.trimEnd() || '(empty)'}\n\`\`\`\nOutput\n\`\`\`\n${ex.expected || '(nothing)'}\n\`\`\`\n\n> Generated from ${origin}. Expected outputs come from running a reference solution — if a test looks wrong, question it.\n`
    const target = path.join(ROOT, 'practice', slug)
    await fs.mkdir(target, { recursive: true })
    await fs.writeFile(path.join(target, 'problem.md'), statement)
    await fs.writeFile(path.join(target, 'main.cpp'), starter)
    await fs.writeFile(path.join(target, 'tests.json'), JSON.stringify({
      title, topic: req.lecture ? `lecture: ${req.lecture}` : String(p.topic ?? 'generated'), difficulty: String(p.difficulty ?? ''),
      language: 'cpp', starter: 'main.cpp', source: 'generated', origin, tests,
    }, null, 2) + '\n')
    await fs.mkdir(path.join(META_DIR, 'solutions'), { recursive: true })
    await fs.writeFile(path.join(META_DIR, 'solutions', `${slug}.cpp`), String(p.solution))
    created.push({ title, starter: `practice/${slug}/main.cpp`, tests: tests.length })
  }
  await fs.rm(work, { recursive: true, force: true })
  return { created, skipped }
}
